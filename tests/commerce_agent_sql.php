<?php
declare(strict_types=1);
require_once __DIR__.'/../includes/bootstrap.php';
if(!in_array('sqlite',PDO::getAvailableDrivers(),true))throw new RuntimeException('pdo_sqlite required for Commerce Agent integration');
function check_scan(bool $condition,string $reason):void{if(!$condition)throw new RuntimeException($reason);}
$db=new PDO('sqlite::memory:');$db->setAttribute(PDO::ATTR_ERRMODE,PDO::ERRMODE_EXCEPTION);
$db->exec('CREATE TABLE commerce_provider_refunds (return_id CHAR(32),initiated_by INTEGER,status VARCHAR(22),updated_at VARCHAR(32))');
$db->exec('CREATE TABLE commerce_return_labels (return_id CHAR(32),purchased_by INTEGER,status VARCHAR(22),updated_at VARCHAR(32))');
$db->exec('CREATE TABLE commerce_connect_transfers (batch_id CHAR(32),authorized_by INTEGER,status VARCHAR(22),updated_at VARCHAR(32))');
$db->exec('CREATE TABLE commerce_payout_batches (id CHAR(32),created_by INTEGER,state VARCHAR(22),updated_at VARCHAR(32))');
$now=strtotime('2026-11-23T09:00:00Z');
$stamp=static fn(int $delta):string=>gmdate('Y-m-d\TH:i:s\Z',$now-$delta);
$id=str_repeat('a',32);
$q=$db->prepare('INSERT INTO commerce_provider_refunds VALUES(?,?,?,?)');
$q->execute([$id,11,'provider_pending',$stamp(2100)]);
$q->execute([str_repeat('b',32),12,'needs_review',$stamp(90000)]);
$q->execute([str_repeat('c',32),13,'ledger_verified',$stamp(90000)]);
$q->execute([str_repeat('d',32),14,'pending',$stamp(500)]);
$db->prepare('INSERT INTO commerce_return_labels VALUES(?,?,?,?)')->execute([str_repeat('e',32),21,'needs_review',$stamp(4000)]);
$db->prepare('INSERT INTO commerce_connect_transfers VALUES(?,?,?,?)')->execute([str_repeat('f',32),22,'pending',$stamp(100000)]);
$db->prepare('INSERT INTO commerce_payout_batches VALUES(?,?,?,?)')->execute([str_repeat('0',32),31,'approved',$stamp(49*3600)]);
$db->prepare('INSERT INTO commerce_payout_batches VALUES(?,?,?,?)')->execute([str_repeat('1',32),32,'paid',$stamp(49*3600)]);
$events=az_commerce_agent_due($db,$now,80);
check_scan(count($events)===5,'Only actionable, aged operations should be scanned');
$kinds=array_count_values(array_column($events,'kind'));
check_scan($kinds['provider_followup']===4&&$kinds['commission_followup']===1,'Provider/payout categorization incorrect');
$keys=array_column($events,'key');
check_scan(count($keys)===count(array_unique($keys)),'Duplicate notification keys within one scan');
check_scan($keys===array_column(az_commerce_agent_due($db,$now,80),'key'),'Unstable notification dedup keys');
check_scan(count(az_commerce_agent_due($db,$now,1))===1,'Bounded scan ignored limit');
$attention=array_values(array_filter($events,static fn($x)=>str_contains($x['key'],$id)));
check_scan(count($attention)===1&&$attention[0]['stage']==='attention','30-minute attention stage missing');
$next=az_commerce_agent_due($db,$now+86400,80);
$escalation=array_values(array_filter($next,static fn($x)=>str_contains($x['key'],$id)));
check_scan(count($escalation)===1&&$escalation[0]['stage']==='overdue','Escalation stage missing');
check_scan($attention[0]['key']!==$escalation[0]['key'],'Escalation would be suppressed by duplicate key');
$json=json_encode($events,JSON_THROW_ON_ERROR);
check_scan(!str_contains($json,'stripe_refund_id')&&!str_contains($json,'payment_intent_id'),'Private provider identifiers leaked');
check_scan($events[0]['priority']===0,'High urgency exception should sort first');
check_scan(str_contains($json,'No bank transfer was initiated'),'Bank confirmation must never be inferred');
print "Commerce Agent SQL scan, dedup and urgency escalation: PASS\n";
